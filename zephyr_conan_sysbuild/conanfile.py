import os

from conan import ConanFile
from conan.tools.cmake import CMakeDeps
from conan.tools.env import Environment
from conan.tools.files import save


class ZephyrConanSysbuildApp(ConanFile):
    """Same firmware as ../zephyr_conan, built through Zephyr's sysbuild.

    Sysbuild configures several CMake projects (here MCUboot + the app) and
    signs the application image. Because Conan hands everything over through
    the *environment* (CMAKE_PREFIX_PATH, ZEPHYR_EXTRA_MODULES, ZEPHYR_BASE,
    the SDK) rather than through ``-D`` cache variables, which sysbuild does
    not forward to its images, nothing changes compared to the single-image
    build except the ``--sysbuild`` flag. Whether MCUboot is included is
    decided in Kconfig.sysbuild, not here.
    """

    name = "zephyr_conan_sysbuild"
    version = "0.1"
    package_type = "application"
    license = "MIT"
    description = "Basic Zephyr sysbuild (MCUboot + app) consuming spdlog/fmt from Conan"

    # The host profile describes the *target* (os=baremetal for MCUs, os=Linux
    # for native_sim); the board option selects the Zephyr board string.
    settings = "os", "arch", "compiler", "build_type"
    options = {"board": ["ANY"]}
    default_options = {
        "board": "native_sim/native/64",
        # Only the west modules this firmware needs; a full workspace is >5 GB.
        # mbedtls + tf-psa-crypto are MCUboot's signature-verification backend.
        "zephyr/*:projects": "hal_stm32,cmsis_6,mcuboot,mbedtls,tf-psa-crypto",
    }

    exports_sources = "CMakeLists.txt", "prj.conf", "Kconfig.sysbuild", "sysbuild/*", "boards/*", "src/*"

    @property
    def _spdlog_supported(self):
        # spdlog needs std::mutex / std::condition_variable / std::thread. The
        # Zephyr SDK's libstdc++ is built without gthreads (Zephyr documents
        # std::thread and std::mutex as unsupported), so on MCUs the app falls
        # back to spdlog's own formatting core, fmt.
        return self.settings.os != "baremetal"

    def requirements(self):
        # Compiled into the firmware, so regular requirements.
        self.requires("zephyr/4.4.0")
        if self._spdlog_supported:
            self.requires("spdlog/1.17.0")
        else:
            self.requires("fmt/12.1.0")

    def build_requirements(self):
        # Toolchains run on the build machine. For native_sim Zephyr's
        # "zephyr" toolchain variant falls back to the host compiler, so one
        # graph serves every board.
        self.tool_requires("zephyr-sdk/1.0.1")

    def layout(self):
        self.folders.source = "."
        self.folders.build = os.path.join("build", str(self.options.board).replace("/", "_"))
        self.folders.generators = os.path.join(self.folders.build, "conan")

    def generate(self):
        # Only the dependency side of the CMake integration, no CMakeToolchain.
        CMakeDeps(self).generate()

        # A Zephyr module is Zephyr's own extension point: its CMakeLists.txt
        # runs inside find_package(Zephyr), before the application's
        # find_package(spdlog). CMakeDeps insists on CMAKE_BUILD_TYPE to pick
        # the configuration of the prebuilt libraries, while Zephyr leaves it
        # unset on purpose; so the module sets Conan's build type and blanks
        # CMake's per-configuration defaults (-O3 -DNDEBUG, ...) that would
        # otherwise leak into every Zephyr translation unit.
        module = os.path.join(self.generators_folder, "conan")
        save(self, os.path.join(module, "zephyr", "module.yml"), "build:\n  cmake: .\n")
        save(
            self,
            os.path.join(module, "CMakeLists.txt"),
            f"""# Generated by conanfile.py: Conan <-> Zephyr build-type reconciliation.
set(CMAKE_BUILD_TYPE {self.settings.build_type} CACHE STRING "Selects the Conan configuration" FORCE)
set(NO_BUILD_TYPE_WARNING ON CACHE BOOL "Optimisation level comes from Kconfig" FORCE)
foreach(lang C CXX ASM)
  foreach(cfg DEBUG RELEASE MINSIZEREL RELWITHDEBINFO)
    set(CMAKE_${{lang}}_FLAGS_${{cfg}} "" CACHE STRING "Zephyr owns the compiler flags" FORCE)
  endforeach()
endforeach()
""",
        )

        env = Environment()
        env.prepend_path("CMAKE_PREFIX_PATH", self.generators_folder)
        env.append("ZEPHYR_EXTRA_MODULES", module, separator=";")
        env.vars(self, scope="build").save_script("conan_zephyr_env")
        # ZEPHYR_BASE, the SDK and PATH come from the dependencies' buildenv_info;
        # Conan applies the aggregated build environment around build().

    @property
    def _west_build_dir(self):
        return os.path.join(self.build_folder, "zephyr")

    def build(self):
        self.run(
            f"west build --sysbuild --pristine=always -b {self.options.board} "
            f"-d {self._west_build_dir} {self.source_folder}"
        )
